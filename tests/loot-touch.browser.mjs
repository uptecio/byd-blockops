import assert from 'node:assert/strict';
import { fixture, freshSolo, emptyControls, soloLoot, selectGrenade, until, onlinePair, moveTo } from './helpers/loot-browser.js';

const f = await fixture({ width: 854, height: 480 });
try {
  await freshSolo(f.pages[0], f.base);
  await emptyControls(f.pages[0]);
  console.log('PASS compact new match exposes disabled loot controls before collecting equipment');
  const page = f.pages[0];
  await soloLoot(page);
  const session = await page.context().newCDPSession(page);
  try {
    const touch = (type, touchPoints = []) => session.send('Input.dispatchTouchEvent', { type, touchPoints });
    const point = async (selector, id) => {
      const b = await page.locator(selector).boundingBox(); assert.ok(b);
      assert.ok(b.x >= 0 && b.y >= 0 && b.x + b.width <= 854 && b.y + b.height <= 480, `${selector} fits compact landscape`);
      assert.ok(b.width >= 44 && b.height >= 44, `${selector} has usable touch target`);
      return { x: b.x + b.width / 2, y: b.y + b.height / 2, id };
    };
    const count = async () => Number((await page.locator('#grenade-type-button').textContent()).match(/(\d)\/3/)[1]);
    const ammo = async () => Number(await page.locator('#ammo-count').textContent());
    const stable = async label => { await page.waitForTimeout(200); const value = await ammo(); await page.waitForTimeout(600); assert.equal(await ammo(), value, label); };
    const stick = await point('#joystick', 1), aim = { x: 450, y: 160, id: 2 }, throwing = await point('#throw-button', 3);
    await page.evaluate(() => {
      window.__touchProof = { aim: 0, cancel: 0 };
      document.querySelector('#aim-zone').addEventListener('pointermove', () => window.__touchProof.aim++);
      document.querySelector('#aim-zone').addEventListener('pointercancel', () => window.__touchProof.cancel++);
    });
    await page.screenshot({ path: 'artifacts/loot-review/loot-controls-854.png' });
    const loaded = await ammo();
    await touch('touchStart', [stick, aim]);
    await touch('touchMove', [{ ...stick, x: stick.x + 20 }, { ...aim, x: aim.x + 25 }]);
    await touch('touchStart', [{ ...stick, x: stick.x + 20 }, { ...aim, x: aim.x + 25 }, throwing]);
    await until(async () => await count() === 2, 'simultaneous move/aim/throw spends one explosive');
    await page.waitForTimeout(1000);
    assert.equal(await count(), 2, 'holding Throw does not repeat or change type');
    assert.equal(await ammo(), loaded, 'throw preserves gun ammunition');
    assert.ok(await page.evaluate(() => window.__touchProof.aim) > 0, 'independent aim finger moves');
    assert.notEqual(await page.locator('#joystick-knob').evaluate(el => el.style.transform), '', 'move finger remains active beside aim/throw');
    await touch('touchEnd');
    assert.equal(await page.locator('#joystick-knob').evaluate(el => el.style.transform), '', 'release centers joystick');
    await selectGrenade(page, 'smoke');
    assert.equal(await count(), 2, 'selecting grenade never throws');
    const fire = await point('#fire-button', 4);
    await touch('touchStart', [stick, aim, fire]);
    await touch('touchMove', [{ ...stick, y: stick.y - 20 }, { ...aim, x: aim.x + 20 }, fire]);
    await page.waitForTimeout(150);
    await touch('touchCancel');
    await page.waitForFunction(() => window.__touchProof.cancel > 0);
    assert.equal(await page.locator('#joystick-knob').evaluate(el => el.style.transform), '');
    await stable('pointer cancellation clears overlapping held fire');
    await touch('touchStart', [fire]);
    await page.waitForTimeout(150);
    await page.locator('#grenade-type-button').click();
    await page.locator('#grenade-picker').waitFor({ state: 'visible' });
    const paused = await ammo(), timer = await page.locator('#timer').textContent();
    await page.locator('#grenade-options [data-grenade-type="flash"]').click();
    assert.equal(await count(), 2, 'type picker selection preserves grenade inventory');
    await page.waitForTimeout(700);
    assert.equal(await ammo(), paused); assert.equal(await page.locator('#timer').textContent(), timer, 'solo picker pauses equipment and match timers');
    await page.screenshot({ path: 'artifacts/loot-review/loot-picker-854.png' });
    await page.locator('#grenade-picker-resume').click();
    await stable('picker resume clears still-held fire'); await touch('touchEnd');
    await stable('late modal release stays neutral');
    const knife = await point('#knife-button', 5);
    await touch('touchStart', [knife]);
    await page.waitForFunction(() => document.querySelector('#fire-button small').textContent === 'SLASH');
    await page.waitForTimeout(800);
    assert.equal(await page.locator('#fire-button small').textContent(), 'SLASH', 'holding knife pointer toggles once');
    assert.equal(await page.locator('#reload-button').isDisabled(), true);
    await touch('touchEnd'); await page.locator('#knife-button').click();
    await page.waitForFunction(() => document.querySelector('#fire-button small').textContent === 'FIRE');
    await touch('touchStart', [stick, fire]); await page.waitForTimeout(150);
    await page.evaluate(() => window.pauseGame());
    await page.waitForSelector('body[data-mode="paused"]');
    const suspensionCount = await count();
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    assert.equal(await page.locator('body').getAttribute('data-mode'), 'paused', 'Android foreground signal waits for explicit Resume');
    await page.locator('#resume-button').click(); await stable('native resume clears fingers held during suspension');
    await touch('touchEnd'); await stable('late suspended release stays neutral');
    assert.equal(await count(), suspensionCount, 'background transition never spends grenades');
    await touch('touchStart', [stick, fire]); await page.waitForTimeout(150);
    await page.locator('#home-button').click(); await page.locator('#cancel-home').click();
    await stable('Home cancel clears held combat'); await touch('touchEnd');
    await page.locator('#home-button').click(); await page.locator('#confirm-home').click();
    await page.locator('#home-solo').click(); await emptyControls(page);
    await stable('new round cannot revive previous fingers');
    console.log('PASS compact three-finger move/aim/throw, hold/release/cancel, picker, knife, Home and Android-style suspension');
    const peers = await onlinePair(f), peer = peers[0];
    await moveTo(page, peer, 0, 12); await moveTo(page, peer, -6, 12);
    await until(() => peer.equipment.grenades.frag === 1, 'touch online player walks onto authored explosive');
    const onlineStick = await point('#joystick', 11), onlineAim = { x: 450, y: 160, id: 12 }, onlineThrow = await point('#throw-button', 13);
    const before = { ...peer.player };
    await touch('touchStart', [onlineStick, onlineAim]);
    await touch('touchMove', [{ ...onlineStick, x: onlineStick.x + 20 }, { ...onlineAim, x: onlineAim.x + 60 }]);
    await touch('touchStart', [{ ...onlineStick, x: onlineStick.x + 20 }, { ...onlineAim, x: onlineAim.x + 60 }, onlineThrow]);
    await until(() => peers.every(p => p.room.gear.projectiles.length === 1), 'both peers see simultaneous touch throw projectile');
    const projectile = peer.room.gear.projectiles[0];
    assert.ok(projectile.vx > 1 && projectile.vz < -10, `online throw uses real current aim drag: ${JSON.stringify(projectile)}`);
    assert.equal(peer.equipment.grenades.frag, 0, 'online touch throw consumes exactly one');
    await until(() => peer.player.x > before.x + .15, 'independent moving finger reaches authoritative simulation during throw');
    await page.waitForTimeout(800);
    assert.equal(peer.events('grenade-throw').length, 1, 'held online Throw creates one action');
    await touch('touchCancel');
    await page.locator('#grenade-type-button').click(); await page.locator('#grenade-picker').waitFor({ state: 'visible' });
    const stopped = { ...peer.player }, clock = peer.room.timeLeft;
    await until(() => peer.room.timeLeft < clock - .4, 'online clock remains live under type picker');
    assert.ok(Math.hypot(peer.player.x - stopped.x, peer.player.z - stopped.z) < .3, 'online picker sends neutral movement');
    await page.locator('#grenade-picker-resume').click();
    await stable('online picker cannot revive cancelled held fire');
    console.log('PASS two compact online peers: simultaneous move/current aim/throw, one held throw, cancellation and neutral live picker');
  } finally { await session.detach(); }
  f.clean();
} finally { await f.close(); }
